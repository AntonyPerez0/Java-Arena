// Java Arena: Math.multiplyHigh(long, long) as implemented in openjdk/jdk21u java.lang.Math,
// copied because TeaVM 0.13.1's class library lacks it. Same license as the file it comes from.

package javaarena.jdk;

final class MultiplyHigh {
    private MultiplyHigh() {
    }

    static long multiplyHigh(long x, long y) {
        long x1 = x >> 32;
        long x2 = x & 0xFFFFFFFFL;
        long y1 = y >> 32;
        long y2 = y & 0xFFFFFFFFL;

        long z2 = x2 * y2;
        long t = x1 * y2 + (z2 >>> 32);
        long z1 = t & 0xFFFFFFFFL;
        long z0 = t >> 32;
        z1 += x2 * y1;

        return x1 * y1 + z0 + (z1 >> 32);
    }
}
