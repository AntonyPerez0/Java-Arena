package yarnstash;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * A YarnDao that keeps the yarn in an H2 database, in the table Yarn. README.md, "Steps", says
 * what each method does and which tests check it.
 */
public class JdbcYarnDao implements YarnDao {
    /** The most characters a name or a shop may have: the columns are VARCHAR(100). */
    private static final int MAX_LENGTH = 100;

    private final String url;

    /**
     * A DAO for the database at this JDBC URL, such as jdbc:h2:./yarnstash (a file) or
     * jdbc:h2:mem:test;DB_CLOSE_DELAY=-1 (in memory, as in the tests).
     */
    public JdbcYarnDao(String url) {
        this.url = url;
        String sql = "CREATE TABLE IF NOT EXISTS Yarn ("
                + "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "name VARCHAR(100) NOT NULL, "
                + "shop VARCHAR(100) NOT NULL, "
                + "skeins INT NOT NULL)";
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.executeUpdate();
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't create the table Yarn", e);
        }
    }

    /** A new connection to the database. Close it when you're done (try-with-resources). */
    private Connection connect() throws SQLException {
        return DriverManager.getConnection(this.url, "sa", "");
    }

    @Override
    public int add(String name, String shop, int skeins) {
        check(name, shop, skeins);
        String sql = "INSERT INTO Yarn (name, shop, skeins) VALUES (?, ?, ?)";
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, name.trim());
            statement.setString(2, shop.trim());
            statement.setInt(3, skeins);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                keys.next();
                return keys.getInt(1);
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't add the yarn", e);
        }
    }

    @Override
    public Yarn findById(int id) {
        String sql = "SELECT id, name, shop, skeins FROM Yarn WHERE id = ?";
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, id);
            try (ResultSet rows = statement.executeQuery()) {
                if (rows.next()) {
                    return yarn(rows);
                }
                return null;
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't read yarn " + id, e);
        }
    }

    @Override
    public List<Yarn> list() {
        String sql = "SELECT id, name, shop, skeins FROM Yarn ORDER BY id";
        List<Yarn> yarns = new ArrayList<>();
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement(sql);
                ResultSet rows = statement.executeQuery()) {
            while (rows.next()) {
                yarns.add(yarn(rows));
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't read the yarn", e);
        }
        return yarns;
    }

    @Override
    public List<Yarn> search(String text) {
        // LOCATE(a, b) is the place of a in b, counted from 1, or 0 if a isn't in b (an empty a
        // gives 1). LIKE would need every %, _ and \ in the text escaped first, since it treats
        // them as wildcards and as its escape character.
        String sql = "SELECT id, name, shop, skeins FROM Yarn "
                + "WHERE LOCATE(LOWER(?), LOWER(name)) > 0 ORDER BY id";
        List<Yarn> yarns = new ArrayList<>();
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, text);
            try (ResultSet rows = statement.executeQuery()) {
                while (rows.next()) {
                    yarns.add(yarn(rows));
                }
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't search the yarn", e);
        }
        return yarns;
    }

    @Override
    public boolean update(Yarn yarn) {
        check(yarn.getName(), yarn.getShop(), yarn.getSkeins());
        String sql = "UPDATE Yarn SET name = ?, shop = ?, skeins = ? WHERE id = ?";
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, yarn.getName().trim());
            statement.setString(2, yarn.getShop().trim());
            statement.setInt(3, yarn.getSkeins());
            statement.setInt(4, yarn.getId());
            return statement.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't change yarn " + yarn.getId(), e);
        }
    }

    @Override
    public boolean remove(int id) {
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement("DELETE FROM Yarn WHERE id = ?")) {
            statement.setInt(1, id);
            return statement.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't remove yarn " + id, e);
        }
    }

    @Override
    public Map<String, Integer> totalsByName() {
        String sql = "SELECT name, SUM(skeins) AS total FROM Yarn GROUP BY name";
        Map<String, Integer> totals = new HashMap<>();
        try (Connection connection = connect();
                PreparedStatement statement = connection.prepareStatement(sql);
                ResultSet rows = statement.executeQuery()) {
            while (rows.next()) {
                totals.put(rows.getString("name"), rows.getInt("total"));
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Couldn't add up the yarn", e);
        }
        return totals;
    }

    /** The yarn on the result set's current row. */
    private static Yarn yarn(ResultSet rows) throws SQLException {
        return new Yarn(rows.getInt("id"), rows.getString("name"),
                rows.getString("shop"), rows.getInt("skeins"));
    }

    /** Throws an IllegalArgumentException if the values can't be stored. */
    private static void check(String name, String shop, int skeins) {
        checkText("name", name);
        checkText("shop", shop);
        if (skeins < 1) {
            throw new IllegalArgumentException("the number of skeins must be at least 1, not " + skeins);
        }
    }

    /** Throws an IllegalArgumentException if the text is empty, or too long once it's trimmed. */
    private static void checkText(String what, String text) {
        if (text == null || text.isBlank()) {
            throw new IllegalArgumentException("the " + what + " is empty");
        }
        int length = text.trim().length();
        if (length > MAX_LENGTH) {
            throw new IllegalArgumentException("the " + what + " has " + length
                    + " characters; at most " + MAX_LENGTH);
        }
    }
}
